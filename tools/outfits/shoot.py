"""Capture specialist outfit renders from the BO3 Personalization screen.
Writes a Lua stepper into the game folder, starts it through the console (keys are posted, the game does not
need focus), then grabs the window whenever the stepper reports a new outfit.
Open Specialists > Personalize on any specialist first. The crop assumes a 2560x1440 game window.
usage: shoot.py pid outdir --game "<BO3 folder>" [--jobs "hero:body:helmet,..."] [--hero N] [--hold 3.2] [--settle 2.7] [--hide 1]"""
import sys, os, time, struct, ctypes, argparse
from ctypes import wintypes
sys.path.insert(0, os.path.dirname(__file__))
import grab, keys
from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument("pid", type=int); ap.add_argument("outdir")
ap.add_argument("--jobs", default=""); ap.add_argument("--hero", type=int, default=-1)
ap.add_argument("--limit", type=int, default=0)
ap.add_argument("--hold", type=float, default=3.2); ap.add_argument("--settle", type=float, default=2.7)
ap.add_argument("--hide", type=int, default=1); ap.add_argument("--full", type=int, default=0)
ap.add_argument("--game", required=True)
a = ap.parse_args()
GAME = a.game
CROP = (960, 110, 2160, 1440)  # character area of the 2560x1440 Personalization screen

k32 = ctypes.WinDLL("kernel32"); psapi = ctypes.WinDLL("psapi")
k32.OpenProcess.restype = wintypes.HANDLE
k32.ReadProcessMemory.argtypes = [wintypes.HANDLE, ctypes.c_void_p, wintypes.LPVOID, ctypes.c_size_t, ctypes.POINTER(ctypes.c_size_t)]
psapi.EnumProcessModulesEx.argtypes = [wintypes.HANDLE, ctypes.c_void_p, wintypes.DWORD, ctypes.POINTER(wintypes.DWORD), wintypes.DWORD]
h = k32.OpenProcess(0x0410, False, a.pid)
mods = (ctypes.c_void_p * 1024)(); need = wintypes.DWORD()
psapi.EnumProcessModulesEx(h, mods, ctypes.sizeof(mods), ctypes.byref(need), 3)
base = 0
for m in mods[:need.value // 8]:
    if not m: continue
    nb = ctypes.create_unicode_buffer(260); psapi.GetModuleBaseNameW(h, ctypes.c_void_p(m), nb, 260)
    if nb.value.lower() == "blackops3.exe": base = m
def rd(addr, n):
    buf = ctypes.create_string_buffer(n); got = ctypes.c_size_t()
    return ctypes.string_at(buf, got.value) if k32.ReadProcessMemory(h, ctypes.c_void_p(addr), buf, n, ctypes.byref(got)) else b""
def hname(s):
    r = 0x4b9ace2f
    for c in s.lower().encode() + b"\0": r = (16777619 * (r ^ c)) & 0xFFFFFFFF
    return r
def find_dvar(name):
    pool = base + 397173280; count = struct.unpack("<i", rd(base + 397173196, 4))[0]
    data = rd(pool, count * 160); hv = hname(name)
    for i in range(count):
        if struct.unpack_from("<I", data, i * 160)[0] == hv: return pool + i * 160
def dvar_string(entry):
    e = rd(entry, 160)
    if len(e) < 160: return ""
    ptr = struct.unpack_from("<Q", e, 40)[0]
    return rd(ptr, 256).split(b"\0")[0].decode("latin-1") if ptr > 0x10000 else ""

if a.jobs:
    jobs_lua = "{" + ",".join("{%s}" % j.replace(":", ",") for j in a.jobs.split(",")) + "}"
else:
    jobs_lua = "nil"
lua = r'''
-- Generated by BoiiiMVM's outfit capture tool. Steps the Personalization character through outfits.
local ok, err = pcall(function()
	local cc = CoD.CCUtility
	local event = cc.Heroes.heroUpdateEvent .. "0"
	local mode = Enum.eModes.MODE_MULTIPLAYER
	local root = LUI.roots.UIRootFull
	local jobs = %s
	if not jobs then
		jobs = {}
		for _, hero in ipairs(Engine.GetHeroList(mode)) do
			if %d < 0 or hero.bodyIndex == %d then
				local custom = Engine.GetHeroCustomizationTable(mode, hero.bodyIndex)
				local bodies, helmets = #custom.bodies, #custom.helmets
				for i = 0, math.max(bodies, helmets) - 1 do
					jobs[#jobs + 1] = { hero.bodyIndex, math.min(i, bodies - 1), math.min(i, helmets - 1) }
				end
			end
		end
	end
	local limit = %d
	local restore = cc.Heroes.HeroIndexForEdits or 0
	local hide = %d == 1
	local hold = %d
	local index, tick, wait_until, hero_now, phase = 0, 0, 30, -1, "next"
	local seq = 0
	local timer
	timer = LUI.UITimer.newElementTimer(100, false, function()
		local good, problem = pcall(function()
			tick = tick + 1
			if tick < wait_until then return end
			if phase == "next" then
				index = index + 1
				local job = jobs[index]
				if not job or (limit > 0 and index > limit) then
					Engine.SendClientScriptNotify(0, event, "changeHero", restore, mode)
					for _, r in pairs(LUI.roots) do
						local child = r:getFirstChild()
						while child do
							if child.mvmHidden then child:setAlpha(1); child.mvmHidden = nil end
							child = child:getNextSibling()
						end
					end
					Engine.SetDvar("mvm_shot", "done|" .. (index - 1))
					root:removeElement(timer)
					return
				end
				if hide then
					-- Hidden roots stop running timers, so the menu's own elements are faded instead.
					for _, r in pairs(LUI.roots) do
						local child = r:getFirstChild()
						while child do
							if child ~= timer and not child.mvmHidden then child:setAlpha(0); child.mvmHidden = true end
							child = child:getNextSibling()
						end
					end
				end
				if job[1] ~= hero_now then
					hero_now = job[1]
					Engine.SendClientScriptNotify(0, event, "changeHero", job[1], mode)
					phase = "body"; wait_until = tick + 8
					return
				end
				phase = "body"
			end
			local job = jobs[index]
			if phase == "body" then
				Engine.SendClientScriptNotify(0, event, "changeBody", job[2], mode)
				phase = "helmet"; wait_until = tick + 2
			elseif phase == "helmet" then
				Engine.SendClientScriptNotify(0, event, "changeHelmet", job[3], mode)
				seq = seq + 1
				Engine.SetDvar("mvm_shot", seq .. "|" .. job[1] .. "|" .. job[2] .. "|" .. job[3] .. "|" .. #jobs)
				phase = "next"; wait_until = tick + hold
			end
		end)
		if not good then Engine.SetDvar("mvm_shot", "error|" .. tostring(problem)); root:removeElement(timer) end
	end)
	root:addElement(timer)
	Engine.SetDvar("mvm_shot", "start|" .. #jobs)
end)
if not ok then Engine.SetDvar("mvm_shot", "error|" .. tostring(err)) end
''' % (jobs_lua, a.hero, a.hero, a.limit, a.hide, int(a.hold * 10))
open(os.path.join(GAME, "MVM", "outfit_shoot.lua"), "w", encoding="utf-8", newline="\n").write(lua)
os.makedirs(a.outdir, exist_ok=True)

hwnd = grab.find_window()
keys.key(0xDF); time.sleep(0.4)
keys.text("lua_exec MVM/outfit_shoot.lua"); time.sleep(0.05); keys.key(0x0D, "\r"); time.sleep(0.3)
keys.key(0xDF)

entry = None; t_end = time.time() + 15
while not entry and time.time() < t_end:
    entry = find_dvar("mvm_shot"); time.sleep(0.2)
if not entry: sys.exit("mvm_shot dvar never appeared")
last = None; due = None; saved = 0; stale = []; t_last = time.time()
while True:
    v = dvar_string(entry)
    if v.startswith("error"): print(v); break
    if v.startswith("done"):
        if due is None: print(v); break
    elif v and not v.startswith("start") and v != last:
        last = v; due = time.time() + a.settle; t_last = time.time()
    if due is not None and time.time() >= due:
        seq, hero, body, helmet, total = last.split("|")
        ok, w, hgt, px = grab.grab(hwnd)
        after = dvar_string(entry)
        im = Image.frombuffer("RGBA", (w, hgt), px, "raw", "BGRA", 0, 1).convert("RGB")
        if not a.full: im = im.crop(CROP)
        name = f"h{int(hero)}_b{int(body):02d}_m{int(helmet):02d}.png"
        im.save(os.path.join(a.outdir, name), compress_level=3)
        saved += 1; due = None
        if after != last and not after.startswith("done"): stale.append(name)
        if saved % 10 == 0 or int(seq) == int(total): print(f"{seq}/{total} {name}", flush=True)
    if time.time() - t_last > 60: print("timeout waiting for the game, last:", v); break
    time.sleep(0.03)
print("saved", saved, "stale", stale)
